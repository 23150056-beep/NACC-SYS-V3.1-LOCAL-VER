// 'check-circle-2' -> 'CheckCircle2', the way lucide-react names its exports.
export function toPascal(name) {
  return String(name)
    .split(/[-_]/)
    .map((p) => p.charAt(0).toUpperCase() + p.slice(1))
    .join('');
}
